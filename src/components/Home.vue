        </p>
        <h3 class="my-5">My First Project</h3>
        <p style="text-indent: 2em;">
          Because we were using Windows servers, licensing costs were high, and I was asked to manage and migrate some application services to Linux while still using VB and C#.
          As a result, some of the servers currently running Windows were downsized.
          We couldn't completely replace them because we were still using Microsoft SQL Server databases.
          Furthermore, during this project, I began implementing the concept of application containerization during deployment, a practice that continues to this day.
          It wasn't a perfect CI/CD pipeline, but it worked, just by utilizing the limited resources we had (physical CPU, RAM, NET, etc.).
        </p>
        <h3 class="my-5">The Next, DB-Link Problem</h3>
        <p style="text-indent: 2em;">
          Before I joined the company, they were using Clipper DB, which they later migrated to Oracle. 
          However, after I joined the team, they asked me to migrate to PostgreSQL for cost-effective reasons.
          I, along with several other people (still considered new employees and expected to be more familiar with the latest technology), began a trial migration.
          We converted the entire existing table structure, views, functions, procedures, CRON jobs / schedulers, and also created extensions that existed in Oracle but weren't available in PostgreSQL.
          Fortunately, our servers are decentralized, so migrating a DC won't disrupt the others.
        </p>
        <p style="text-indent: 2em;">
          Oracle has a feature called dblink that makes it easy to retrieve data between database servers, for example, from all branches to the head office (actually, PostgreSQL also has one).
          However, since we're starting the migration one branch at a time, I had to think about replacing this feature, as it only works for the same database.
          So, I created a REST API (initially) as a prototype for retrieving data.
          After testing, I found this method unreliable for sending large amounts of data, so I decided to use Kafka and GRPC for data streaming.
          This was a side project that eventually evolved into a serious project and became the main foundation for large-scale, real-time data transfers.
        </p>
